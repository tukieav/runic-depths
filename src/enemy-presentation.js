export function enemyPresentation(typeOrEntity) {
  const type =
    typeof typeOrEntity === 'string' ? typeOrEntity : (typeOrEntity?.type ?? typeOrEntity?.id);
  return Object.hasOwn(ENEMY_PRESENTATION, type) ? ENEMY_PRESENTATION[type] : null;
}
